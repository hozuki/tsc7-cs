namespace TypeScript.Printer;

/// <summary>Go 的 <c>type GeneratedIdentifierFlags int</c>：自动生成标识符的种类位 + 标志位。</summary>
public enum GeneratedIdentifierFlags
{
    // Kind

    /// <summary>Not automatically generated.</summary>
    None = 0,
    /// <summary>Automatically generated identifier.</summary>
    Auto = 1,
    /// <summary>Automatically generated identifier with a preference for '_i'.</summary>
    Loop = 2,
    /// <summary>Unique name based on the 'text' property.</summary>
    Unique = 3,
    /// <summary>Unique name based on the node in the 'Node' property.</summary>
    Node = 4,
    /// <summary>Mask to extract the kind of identifier from its flags.</summary>
    KindMask = 7,

    // Flags

    /// <summary>Reserve the generated name in nested scopes.</summary>
    ReservedInNestedScopes = 1 << 3,
    /// <summary>First instance won't use '_#' if there's no conflict.</summary>
    Optimistic = 1 << 4,
    /// <summary>Use only the file identifiers list and not generated names to search for conflicts.</summary>
    FileLevel = 1 << 5,
    /// <summary>
    /// Used by `module.ts` to indicate generated nodes which can have substitutions performed upon them
    /// (as they were generated by an earlier transform phase).
    /// </summary>
    AllowNameSubstitution = 1 << 6,
}

/// <summary>Go 的 <c>GeneratedIdentifierFlags</c> 上的方法（见文件头说明）。</summary>
public static class GeneratedIdentifierFlagsExtensions
{
    /// <summary>Go: <c>func (f GeneratedIdentifierFlags) Kind() GeneratedIdentifierFlags</c>。</summary>
    public static GeneratedIdentifierFlags Kind(this GeneratedIdentifierFlags f) => f & GeneratedIdentifierFlags.KindMask;

    /// <summary>Go: <c>func (f GeneratedIdentifierFlags) IsAuto() bool</c>。</summary>
    public static bool IsAuto(this GeneratedIdentifierFlags f) => f.Kind() == GeneratedIdentifierFlags.Auto;

    /// <summary>Go: <c>func (f GeneratedIdentifierFlags) IsLoop() bool</c>。</summary>
    public static bool IsLoop(this GeneratedIdentifierFlags f) => f.Kind() == GeneratedIdentifierFlags.Loop;

    /// <summary>Go: <c>func (f GeneratedIdentifierFlags) IsUnique() bool</c>。</summary>
    public static bool IsUnique(this GeneratedIdentifierFlags f) => f.Kind() == GeneratedIdentifierFlags.Unique;

    /// <summary>Go: <c>func (f GeneratedIdentifierFlags) IsNode() bool</c>。</summary>
    public static bool IsNode(this GeneratedIdentifierFlags f) => f.Kind() == GeneratedIdentifierFlags.Node;

    /// <summary>Go: <c>func (f GeneratedIdentifierFlags) IsReservedInNestedScopes() bool</c>。</summary>
    public static bool IsReservedInNestedScopes(this GeneratedIdentifierFlags f) =>
        (f & GeneratedIdentifierFlags.ReservedInNestedScopes) != 0;

    /// <summary>Go: <c>func (f GeneratedIdentifierFlags) IsOptimistic() bool</c>。</summary>
    public static bool IsOptimistic(this GeneratedIdentifierFlags f) =>
        (f & GeneratedIdentifierFlags.Optimistic) != 0;

    /// <summary>Go: <c>func (f GeneratedIdentifierFlags) IsFileLevel() bool</c>。</summary>
    public static bool IsFileLevel(this GeneratedIdentifierFlags f) => (f & GeneratedIdentifierFlags.FileLevel) != 0;

    /// <summary>Go: <c>func (f GeneratedIdentifierFlags) HasAllowNameSubstitution() bool</c>。</summary>
    public static bool HasAllowNameSubstitution(this GeneratedIdentifierFlags f) =>
        (f & GeneratedIdentifierFlags.AllowNameSubstitution) != 0;
}
