// tools/TypeScript.CodeGen 的 AST 生成器。
//
// 输入：<TSGO_ROOT>/tools/scripts/tsc/ast.json（语言中立模型）+ TSGO 的判定逻辑
//       tools/scripts/tsc/generate-go-ast.ts（1107 行）——本生成器逐条搬运它的判定：
//       哪些 base 是零尺寸、mixin 采集、update 工厂的比较列表、ForEachChild 的子节点列表、
//       VisitEachChild、Clone、subtree facts、kind 别名守卫、name accessor；只把输出语法从 Go 换成 C#。
// 输出：<out>/Nodes.Generated.cs、Kind.Generated.cs、KindStringer.Generated.cs。
// C# 表示（mixin 接口、字段平铺、显式接口转发、`new` 修饰、`panic` → 异常）见 docs/ast.md §2/§3。
//
// 用法：
//   dotnet run --project tools/TypeScript.CodeGen -- [--tsgo-root <path>] [--out <dir>]
//   TSGO 根目录优先级：--tsgo-root > 环境变量 TSGO_ROOT > D:\Source\GitHub\TypeScript-Go
//   --out 缺省 src/TypeScript.Compiler/Ast
//
// 幂等：输出只由输入内容决定（文件头写的是相对 TSGO 的路径），连续两次运行字节一致；内容未变化不重写。
using System.Globalization;
using System.Text;

namespace TypeScript.CodeGen;

internal static class GoAstGenerator
{
    private const string _astJsonRelativePath = "tools/scripts/tsc/ast.json";

    /// <summary>生成三个文件，返回实际被重写的文件路径（内容未变化则为空）。</summary>
    public static List<string> Generate(string tsgoRoot, string outDir)
    {
        var jsonPath = Path.Combine(tsgoRoot, _astJsonRelativePath.Replace('/', Path.DirectorySeparatorChar));
        if (!File.Exists(jsonPath))
        {
            throw new FileNotFoundException(
                $"找不到 TSGO 输入文件：{jsonPath}。用 --tsgo-root <path> 或环境变量 TSGO_ROOT 指定 TSGO 仓库根目录。",
                jsonPath);
        }

        var schema = AstSchema.Load(File.ReadAllText(jsonPath));
        Directory.CreateDirectory(outDir);

        var written = new List<string>();
        WriteIfChanged(Path.Combine(outDir, "Nodes.Generated.cs"), RenderNodes(schema), written);
        WriteIfChanged(Path.Combine(outDir, "Kind.Generated.cs"), RenderKind(schema), written);
        WriteIfChanged(Path.Combine(outDir, "KindStringer.Generated.cs"), RenderKindStringer(schema), written);
        return written;
    }

    // 内容相同则不写、不改时间戳（便于将来接入构建）。
    private static void WriteIfChanged(string path, string content, List<string> written)
    {
        if (File.Exists(path) && File.ReadAllText(path) == content)
        {
            return;
        }

        File.WriteAllText(path, content, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        written.Add(path);
    }

    private static void AppendHeader(StringBuilder sb, string portedFrom, string outDir)
    {
        sb.Append("// <auto-generated>\n");
        sb.Append("// This file was generated by tools/TypeScript.CodeGen (GoAstGenerator.cs). DO NOT EDIT.\n");
        sb.Append("// 请勿手工编辑：修改输入后重新运行\n");
        sb.Append("//   dotnet run --project tools/TypeScript.CodeGen -- --out ").Append(outDir.Replace('\\', '/')).Append('\n');
        sb.Append("// 输入：tools/scripts/tsc/ast.json（相对 TSGO 根目录）\n");
        sb.Append("// 判定依据：TSGO 的 tools/scripts/tsc/generate-go-ast.ts（输出语法换成 C#）\n");
        sb.Append("// </auto-generated>\n");
        sb.Append("// ported from: ").Append(portedFrom).Append('\n');
        // 生成文件带 <auto-generated> 头，Roslyn 默认不为它们开启可空注解上下文（否则每个 `T?` 都是 CS8669）。
        sb.Append("#nullable enable\n");
    }

