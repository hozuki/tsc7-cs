    private static string RenderKindStringer(AstSchema schema)
    {
        var sb = new StringBuilder();
        AppendHeader(sb, "internal/ast/kind_stringer_generated.go", _outDirDisplay);
        sb.Append("//\n");
        sb.Append("// Go 的 kind_stringer_generated.go 用 stringer 生成 _Kind_name + _Kind_index；这里等价地生成\n");
        sb.Append("// 名字数组（逐字相同的文本：每个成员是 \"Kind\" + 枚举成员名），越界值同样返回 \"Kind(<n>)\"。\n");
        sb.Append("using System.Globalization;\n");
        sb.Append('\n');
        sb.Append("namespace TypeScript.Ast;\n");
        sb.Append('\n');
        sb.Append("public static partial class Ast\n");
        sb.Append("{\n");
        sb.Append("    private static readonly string[] _kindNames =\n    [\n");
        foreach (var element in schema.KindElements)
        {
            if (element.Name is null)
            {
                continue;
            }

            sb.Append("        \"Kind").Append(element.Name).Append("\",\n");
        }

        // Go 的 stringer 把 KindCount 也算进名字表（值 351 的文本是 "KindCount"），这里逐字保持一致。
        sb.Append("        \"KindCount\",\n");
        sb.Append("    ];\n");
        sb.Append('\n');
        sb.Append("    // Go: func (i Kind) String() string\n");
        sb.Append("    public static string String(this Kind value)\n");
        sb.Append("    {\n");
        sb.Append("        var index = (int)value;\n");
        sb.Append("        if (index < 0 || index >= _kindNames.Length)\n");
        sb.Append("        {\n");
        sb.Append("            return \"Kind(\" + ((int)value).ToString(CultureInfo.InvariantCulture) + \")\";\n");
        sb.Append("        }\n");
        sb.Append("\n");
        sb.Append("        return _kindNames[index];\n");
        sb.Append("    }\n");
        sb.Append("}\n");
        return sb.ToString();
    }

    internal static string LowerFirst(string name)
    {
        if (name.StartsWith("JSDoc", StringComparison.Ordinal))
        {
            return "jsdoc" + name[5..];
        }

        return char.ToLowerInvariant(name[0]) + name[1..];
    }
