    private static string RenderKind(AstSchema schema)
    {
        var sb = new StringBuilder();
        AppendHeader(sb, "internal/ast/kind_generated.go", _outDirDisplay);
        sb.Append('\n');
        sb.Append("namespace TypeScript.Ast;\n");
        sb.Append('\n');
        sb.Append("// 数值与 Go 的 kind_generated.go 完全一致（Kind 值会出现在 baseline 里）。\n");
        sb.Append("public enum Kind : short\n");
        sb.Append("{\n");

        var index = 0;
        foreach (var element in schema.KindElements)
        {
            if (element.Name is null)
            {
                sb.Append("    // ").Append(element.Comment).Append('\n');
                continue;
            }

            sb.Append("    ").Append(element.Name).Append(" = ").Append(index.ToString(CultureInfo.InvariantCulture)).Append(',');
            if (element.Comment is not null)
            {
                sb.Append(" // ").Append(element.Comment);
            }

            sb.Append('\n');
            index++;
        }

        sb.Append("    Count = ").Append(index.ToString(CultureInfo.InvariantCulture)).Append(',');
        sb.Append('\n');
        foreach (var marker in schema.KindMarkers)
        {
            sb.Append("    ").Append(marker.Name).Append(" = ").Append(ResolveMarker(schema, marker.Value)).Append(',');
            sb.Append('\n');
        }

        sb.Append("}\n");
        return sb.ToString();
    }

    private static string ResolveMarker(AstSchema schema, string value)
    {
        // marker 的值可能是另一个 marker（Go 的 kind_generated.go 直接写 Kind<value>，C# 这里展开成最终成员名）。
        foreach (var marker in schema.KindMarkers)
        {
            if (marker.Name == value)
            {
                return ResolveMarker(schema, marker.Value);
            }
        }

        return value;
    }

