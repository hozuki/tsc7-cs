    internal const string _outDirDisplay = "src/TypeScript.Compiler/Ast";

    private static string RenderNodes(AstSchema schema)
    {
        var w = new CodeWriter();
        var sb = new StringBuilder();
        AppendHeader(sb, "internal/ast/ast_generated.go", _outDirDisplay);
        sb.Append("//\n");
        sb.Append("// C# 侧与 Go 生成物的结构性差异（docs/ast.md §2/§3）：\n");
        sb.Append("//   1. Go 用结构体内嵌 mixin；C# 无多重继承，所以把 mixin 字段平铺进节点类，并用\n");
        sb.Append("//      接口（I<基础名>）+ 显式接口实现转发暴露它们（`d := n.DeclarationData(); d.Symbol`）。\n");
        sb.Append("//   2. 与 Node 访问器同名的字段加 `new`（Go 里字段/方法同名同样会遮蔽：`id.Text` 选字段）。\n");
        sb.Append("//   3. Go 的 panic(...) → throw new DebugFailureException(...)（Debug.Fail 的包装，直接 throw 便于控制流）。\n");
        sb.Append("//   4. 没有 arena（节点是 class），工厂里的 `data := f.xxxArena.New()` → `new Xxx()`。\n");
        sb.Append("//   5. Node 上 `SubtreeFacts`/`ModifierFlags`/`Symbol` 写成**属性**而不是方法：它们的名字与返回类型名相同，\n");
        sb.Append("//      而 C# 里方法会遮蔽类型名（`SubtreeFacts.None` 会解析不到类型），属性不会（Color Color 规则）。\n");
        sb.Append("//      调用点由 Go 的 `x.SubtreeFacts()` 改成 `x.SubtreeFacts`。\n");
        sb.Append("using System.Threading;\n");
        sb.Append("using static TypeScript.Core.Core;\n");
        sb.Append('\n');
        sb.Append("namespace TypeScript.Ast;\n");
        w.WriteRaw(sb.ToString());

        // ── NodeFactory ──
        w.Write("");
        w.Write("// ──────────────────────────────────────────────────────────────────────");
        w.Write("// NodeFactory（每个节点的工厂 + update 工厂）");
        w.Write("// ──────────────────────────────────────────────────────────────────────");
        w.Write("");
        w.Write("public partial class NodeFactory");
        w.Write("{");
        w.Push();
        foreach (var node in schema.Nodes)
        {
            if (node.HandWritten)
            {
                continue;
            }

            w.Write("");
            w.WriteLineComment($"// {node.Key}: New{node.Key} / Update{node.Key}");
            EmitNewFactory(schema, w, node);
            EmitUpdateFactory(schema, w, node);
        }

        w.Pop();
        w.Write("}");

        // ── 基础接口 ──
        w.Write("");
        w.Write("// ──────────────────────────────────────────────────────────────────────");
        w.Write("// mixin 基础接口（Go 的内嵌基础结构体；零尺寸/brand 基础只有接口、没有成员）");
        w.Write("// ──────────────────────────────────────────────────────────────────────");
        foreach (var baseEntry in schema.Bases)
        {
            w.Write("");
            EmitBaseInterface(schema, w, baseEntry);
        }

        // ── 节点类 ──
        foreach (var node in schema.Nodes)
        {
            w.Write("");
            w.Write("// ──────────────────────────────────────────────────────────────────────");
            w.Write($"// {node.Key}");
            w.Write("// ──────────────────────────────────────────────────────────────────────");
            w.Write("");
            if (node.HandWritten)
            {
                w.WriteLineComment($"// Struct and factory methods hand-written in ./{node.Key}.cs");
                continue;
            }

            EmitNodeClass(schema, w, node);
        }

        // ── As 转换 ──
        w.Write("");
        w.Write("// ──────────────────────────────────────────────────────────────────────");
        w.Write("// As*() cast methods");
        w.Write("// ──────────────────────────────────────────────────────────────────────");
        w.Write("");
        w.Write("public abstract partial class Node");
        w.Write("{");
        w.Push();
        foreach (var node in schema.Nodes)
        {
            w.Write("");
            w.WriteLineComment($"// Go: func (n *Node) As{node.Key}() *{node.Key} {{ return n.data.(*{node.Key}) }}");
            w.Write($"public {node.Key}? As{node.Key}() => this as {node.Key};");
        }

        w.Pop();
        w.Write("}");

        // ── Is 函数 + kind 别名守卫 ──
        w.Write("");
        w.Write("// ──────────────────────────────────────────────────────────────────────");
        w.Write("// Is*() 类型判断（Go 的包级函数）");
        w.Write("// ──────────────────────────────────────────────────────────────────────");
        w.Write("");
        w.Write("public static partial class Ast");
        w.Write("{");
        w.Push();
        foreach (var node in schema.Nodes)
        {
            w.Write("");
            EmitIsFunctions(schema, w, node);
        }

        EmitKindAliasGuards(schema, w);
        w.Pop();
        w.Write("}");
        w.Write("");

        return w.ToString();
    }

    private static void EmitNewFactory(AstSchema schema, CodeWriter w, NodeDef node)
    {
        var members = schema.SchemaMembers(node);
        EmitNewFactoryCore(schema, w, $"New{node.Key}", node, members, kindArg: null);
        for (var i = 1; i < node.Kinds.Count; i++)
        {
            // Go 的 generate-go-ast.ts 给每个 kind 都发射一个工厂，别名工厂用的是**别名自己的 kind**
            // （ast_generated.go:2272 `NewJSTypeAliasDeclaration` → `newNode(KindJSTypeAliasDeclaration, …)`）。
            // 这里之前漏传 kindArg，导致别名工厂造出基类 kind 的节点（Update 的 `case Kind.别名` 分支因此不可达）。
            // 节点自己有 kind 参数（Kind 成员）时仍以参数为准，与 Go 的该形态工厂一致。
            var hasKindMember = members.Any(m => schema.IsKindMember(m, node));
            EmitNewFactoryCore(schema, w, $"New{node.Kinds[i]}", node, members,
                kindArg: hasKindMember ? null : $"Kind.{node.Kinds[i]}");
        }
    }

    private static void EmitNewFactoryCore(
        AstSchema schema,
        CodeWriter w,
        string methodName,
        NodeDef node,
        List<MemberDef> members,
        string? kindArg)
    {
        var parameters = new List<string>();
        foreach (var member in members)
        {
            parameters.Add($"{schema.CsType(member, node)} {schema.CsParamName(member.Name)}");
        }

        var kindMember = members.FirstOrDefault(m => schema.IsKindMember(m, node));
        var kindExpression = kindArg ?? (kindMember is not null
            ? schema.CsParamName(kindMember.Name)
            : $"Kind.{node.PrimaryKind}");

        w.Write($"public Node {methodName}({string.Join(", ", parameters)})");
        w.Write("{");
        w.Push();
        w.Write($"var data = new {node.Key}();");
        foreach (var member in members)
        {
            if (schema.IsKindMember(member, node) || schema.IsNodeFlagsMember(member))
            {
                continue;
            }

            var value = member.Bitmask is null
                ? schema.CsParamName(member.Name)
                : $"{schema.CsParamName(member.Name)} & {schema.CsBitmask(member.Bitmask)}";
            w.Write($"data.{schema.CsFieldName(member.Name, member.Private)} = {value};");
        }

        if (schema.HasTextContent(node))
        {
            w.Write("_textCount++;");
        }

        var nodeFlagsMembers = members.Where(m => schema.IsNodeFlagsMember(m)).ToList();
        if (nodeFlagsMembers.Count == 0)
        {
            w.Write($"return NewNode({kindExpression}, data);");
        }
        else
        {
            w.Write($"var node = NewNode({kindExpression}, data);");
            foreach (var member in nodeFlagsMembers)
            {
                var param = schema.CsParamName(member.Name);
                w.Write(member.Bitmask is null
                    ? $"node.Flags = {param};"
                    : $"node.Flags |= {param} & {schema.CsBitmask(member.Bitmask)};");
            }

            w.Write("return node;");
        }

        w.Pop();
        w.Write("}");
        w.Write("");
    }

    private static void EmitUpdateFactory(AstSchema schema, CodeWriter w, NodeDef node)
    {
        var members = schema.SchemaMembers(node);
        var updateMembers = members.Where(m => !schema.IsKindMember(m, node)).ToList();
        if (updateMembers.Count == 0)
        {
            return;
        }

        // 叶子节点（没有子 AST 成员）不生成 Update 方法。
        if (!updateMembers.Any(m => schema.IsChild(m, node)))
        {
            return;
        }

        var parameters = new List<string> { $"{node.Key} node" };
        foreach (var member in updateMembers)
        {
            parameters.Add($"{schema.CsType(member, node)} {schema.CsParamName(member.Name)}");
        }

        var comparisons = updateMembers.Select(member =>
        {
            var param = schema.CsParamName(member.Name);
            var field = schema.CsFieldName(member.Name, member.Private);
            return schema.IsRawList(member, node)
                ? $"!Same({param}, node.{field})"
                : $"{param} != node.{field}";
        });

        var newArgs = members.Select(member => schema.IsKindMember(member, node)
            ? "node.Kind"
            : schema.CsParamName(member.Name));

        w.Write($"public Node Update{node.Key}({string.Join(", ", parameters)})");
        w.Write("{");
        w.Push();
        w.Write($"if ({string.Join(" || ", comparisons)})");
        w.Write("{");
        w.Push();
        if (node.Kinds.Count > 1)
        {
            w.Write("switch (node.Kind)");
            w.Write("{");
            w.Push();
            w.Write($"case Kind.{node.PrimaryKind}:");
            w.Push();
            w.Write($"return Ast.UpdateNode(New{node.Key}({string.Join(", ", newArgs)}), node, _hooks);");
            w.Pop();
            for (var i = 1; i < node.Kinds.Count; i++)
            {
                w.Write($"case Kind.{node.Kinds[i]}:");
                w.Push();
                w.Write($"return Ast.UpdateNode(New{node.Kinds[i]}({string.Join(", ", newArgs)}), node, _hooks);");
                w.Pop();
            }

            w.Write("default:");
            w.Push();
            w.Write($"throw new DebugFailureException(\"unexpected kind in Update{node.Key}: \" + node.Kind.String());");
            w.Pop();
            w.Pop();
            w.Write("}");
        }
        else
        {
            w.Write($"return Ast.UpdateNode(New{node.Key}({string.Join(", ", newArgs)}), node, _hooks);");
        }

        w.Pop();
        w.Write("}");
        w.Write("");
        w.Write("return node;");
        w.Pop();
        w.Write("}");
        w.Write("");
    }

    private static void EmitBaseInterface(AstSchema schema, CodeWriter w, BaseEntry baseEntry)
    {
        var extends = baseEntry.Extends.Select(e => "I" + e).ToList();
        var header = $"public interface I{baseEntry.Key}";

        w.WriteLineComment($"// Go: type {baseEntry.Key} struct");
        w.Write(extends.Count == 0 ? header : $"{header} : {string.Join(", ", extends)}");
        w.Write("{");
        w.Push();
        w.WriteLineComment("// Go 的内嵌基础字段：导出字段 → 显式接口实现的属性；未导出字段（name/modifiers/facts）不进接口。");
        var wrote = false;
        foreach (var field in schema.ExportedInterfaceFields(baseEntry))
        {
            wrote = true;
            w.Write($"{schema.CsFieldType(field)} {field.Name} {{ get; set; }}");
        }

        if (baseEntry.Key == "CompositeBase")
        {
            wrote = true;
            w.WriteLineComment("// Go: facts atomic.Uint32（Node.SubtreeFacts 的缓存；Go 里未导出，所以接口成员是 internal）");
            w.Write("internal int Facts { get; set; }");
        }

        if (!wrote)
        {
            w.WriteLineComment("// 零尺寸 / brand 基础：只有接口，没有成员");
        }

        w.Pop();
        w.Write("}");
    }

    private static void EmitNodeClass(AstSchema schema, CodeWriter w, NodeDef node)
    {
        var interfaces = new List<string> { "Node" };
        interfaces.AddRange(node.Extends.Select(e => "I" + e));
        w.WriteLineComment($"// Go: type {node.Key} struct {{ {string.Join("; ", node.Extends)} ... }}");
        w.Write($"public sealed partial class {node.Key} : {string.Join(", ", interfaces)}");
        w.Write("{");
        w.Push();

        // 字段：节点专有成员 + 平铺进来的 mixin 基础字段（Go 用内嵌，C# 无多重继承）。
        foreach (var field in schema.ClassFields(node))
        {
            w.WriteLineComment($"// Go: {field.Owner}.{field.Name}");
            w.Write(field.IsString && !field.Optional
                ? $"{field.Modifier} {field.CsType} {field.CsName} = \"\";"
                : $"{field.Modifier} {field.CsType} {field.CsName};");
        }

        // 显式接口实现转发。
        foreach (var forward in schema.InterfaceForwards(node))
        {
            w.Write($"{forward.CsType} I{forward.Owner}.{forward.Name} {{ get => {forward.CsName}; set => {forward.CsName} = value; }}");
        }

        if (schema.HasBase(node, "CompositeBase"))
        {
            w.WriteLineComment("// Go: facts atomic.Uint32 的 Load/Store（C# 用 Volatile 保持原子性）");
            w.Write("int ICompositeBase.Facts { get => Volatile.Read(ref _facts); set => Volatile.Write(ref _facts, value); }");
        }

        // 基础访问器覆写（Go 由内嵌基础的方法集提供）。
        foreach (var dataAccessor in schema.DataAccessors(node))
        {
            w.WriteLineComment($"// Go: {dataAccessor.Owner}.{dataAccessor.Name}()");
            w.Write($"public override {dataAccessor.ReturnType} {dataAccessor.Name}() => this;");
        }

        if (schema.HasField(node, "_name"))
        {
            w.WriteLineComment("// Go: NamedMemberBase/ClassLikeBase 的私有 name 字段 + Name() 方法");
            w.Write("public override Node? Name() => _name;");
        }

        if (schema.HasField(node, "_modifiers"))
        {
            w.WriteLineComment("// Go: ModifiersBase.Modifiers()/setModifiers");
            w.Write("public override ModifierList? Modifiers() => _modifiers;");
            w.Write("public override void SetModifiers(ModifierList? modifiers) => _modifiers = modifiers;");
        }

        EmitForEachChild(schema, w, node);
        EmitVisitEachChild(schema, w, node);
        EmitClone(schema, w, node);
        EmitComputeSubtreeFacts(schema, w, node);

        w.Pop();
        w.Write("}");
    }

    private static void EmitForEachChild(AstSchema schema, CodeWriter w, NodeDef node)
    {
        var children = schema.SchemaMembers(node).Where(m => schema.IsChild(m, node)).ToList();
        if (children.Count == 0)
        {
            return;
        }

        w.WriteLineComment("// Go: func (node *X) ForEachChild(v Visitor) bool");
        w.Write("public override bool ForEachChild(Visitor v)");
        w.Write("{");
        w.Push();
        if (node.HandWrittenVisitor)
        {
            w.Write($"return Ast.ForEachChild{node.Key}(this, v);");
            w.Pop();
            w.Write("}");
            w.Write("");
            return;
        }

        var parts = children.Select(m => schema.ForEachChildPart(m, node)).ToList();
        if (parts.Count <= 3)
        {
            w.Write($"return {string.Join(" || ", parts)};");
        }
        else
        {
            var pad = new string(' ', "return ".Length);
            for (var i = 0; i < parts.Count; i++)
            {
                var prefix = i == 0 ? "return " : pad;
                var suffix = i == parts.Count - 1 ? ";" : " ||";
                w.Write(prefix + parts[i] + suffix);
            }
        }

        w.Pop();
        w.Write("}");
        w.Write("");
    }

    private static void EmitVisitEachChild(AstSchema schema, CodeWriter w, NodeDef node)
    {
        var members = schema.SchemaMembers(node);
        var children = members.Where(m => schema.IsChild(m, node)).ToList();
        if (children.Count == 0)
        {
            return;
        }

        w.WriteLineComment("// Go: func (node *X) VisitEachChild(v *NodeVisitor) *Node");
        w.Write("public override Node? VisitEachChild(NodeVisitor v)");
        w.Write("{");
        w.Push();
        if (node.HandWrittenVisitor)
        {
            w.Write($"return Ast.VisitEachChild{node.Key}(this, v);");
            w.Pop();
            w.Write("}");
            w.Write("");
            return;
        }

        var updateMembers = members.Where(m => !schema.IsKindMember(m, node)).ToList();
        var rawLocals = new Dictionary<string, string>();
        foreach (var member in updateMembers)
        {
            if (schema.IsChild(member, node) && schema.IsRawList(member, node))
            {
                var local = LowerFirst(member.Name);
                rawLocals[member.Name] = local;
                w.Write($"var {local} = SameMap({schema.CsFieldName(member.Name, member.Private)}, n => v.VisitNodeWithHooks(n)!);");
            }
        }

        var args = new List<string>();
        foreach (var member in updateMembers)
        {
            if (!schema.IsChild(member, node))
            {
                args.Add(schema.CsFieldName(member.Name, member.Private));
                continue;
            }

            if (rawLocals.TryGetValue(member.Name, out var local))
            {
                args.Add(local);
                continue;
            }

            var access = schema.CsFieldName(member.Name, member.Private);
            args.Add(schema.VisitMethod(member) + $"({access})");
        }

        w.Write($"return v.Factory.Update{node.Key}(this, {string.Join(", ", args)});");
        w.Pop();
        w.Write("}");
        w.Write("");
    }

    private static void EmitClone(AstSchema schema, CodeWriter w, NodeDef node)
    {
        var members = schema.SchemaMembers(node);
        w.WriteLineComment("// Go: func (node *X) Clone(f NodeFactoryCoercible) *Node");
        w.Write("public override Node? Clone(NodeFactoryCoercible f)");
        w.Write("{");
        w.Push();
        var args = members.Select(member =>
        {
            if (schema.IsKindMember(member, node))
            {
                return "Kind";
            }

            if (member.Inherited && member.DeclaredAliasName == "ModifierLike")
            {
                return "Modifiers()";
            }

            return schema.CsFieldName(member.Name, member.Private);
        });
        var argList = string.Join(", ", args);

        if (node.Kinds.Count > 1)
        {
            w.Write("switch (Kind)");
            w.Write("{");
            w.Push();
            w.Write($"case Kind.{node.PrimaryKind}:");
            w.Push();
            w.Write($"return Ast.CloneNode(f.AsNodeFactory().New{node.Key}({argList}), this, f.AsNodeFactory()._hooks);");
            w.Pop();
            for (var i = 1; i < node.Kinds.Count; i++)
            {
                w.Write($"case Kind.{node.Kinds[i]}:");
                w.Push();
                w.Write($"return Ast.CloneNode(f.AsNodeFactory().New{node.Kinds[i]}({argList}), this, f.AsNodeFactory()._hooks);");
                w.Pop();
            }

            w.Write("default:");
            w.Push();
            w.Write($"throw new DebugFailureException(\"unexpected kind in {node.Key}.Clone: \" + Kind.String());");
            w.Pop();
            w.Pop();
            w.Write("}");
        }
        else
        {
            w.Write($"return Ast.CloneNode(f.AsNodeFactory().New{node.Key}({argList}), this, f.AsNodeFactory()._hooks);");
        }

        w.Pop();
        w.Write("}");
        w.Write("");
    }

    private static void EmitComputeSubtreeFacts(AstSchema schema, CodeWriter w, NodeDef node)
    {
        if (!node.GenerateSubtreeFacts)
        {
            return;
        }

        var children = schema.SchemaMembers(node).Where(m => schema.IsChild(m, node)).ToList();
        w.WriteLineComment("// Go: func (node *X) computeSubtreeFacts() SubtreeFacts");
        w.Write("internal override SubtreeFacts ComputeSubtreeFacts()");
        w.Write("{");
        w.Push();
        if (children.Count == 0)
        {
            w.Write("return SubtreeFacts.None;");
        }
        else
        {
            for (var index = 0; index < children.Count; index++)
            {
                var term = schema.SubtreeFactsTerm(children[index], node);
                var isLast = index == children.Count - 1;
                var prefix = index == 0 ? "return " : "";
                w.Write($"{prefix}{term}{(isLast ? ";" : " |")}");
            }
        }

        w.Pop();
        w.Write("}");
    }

    private static void EmitIsFunctions(AstSchema schema, CodeWriter w, NodeDef node)
    {
        var kindTypes = schema.KindTypes(node);
        if (node.KindTypeIsTypeParameter)
        {
            w.WriteLineComment($"// Go: func Is{node.Key}(node *Node) bool（kind 是类型参数，按 node.Kind switch）");
            w.Write($"public static bool Is{node.Key}(Node node)");
            w.Write("{");
            w.Push();
            w.Write("switch (node.Kind)");
            w.Write("{");
            w.Push();
            foreach (var kind in kindTypes)
            {
                w.Write($"case Kind.{kind}:");
            }

            w.Push();
            w.Write("return true;");
            w.Pop();
            w.Pop();
            w.Write("}");
            w.Write("");
            w.Write("return false;");
            w.Pop();
            w.Write("}");
            w.Write("");
            return;
        }

        if (kindTypes.Count > 1)
        {
            // Go: isMultiKind() —— 每个 kind 一个 Is 函数（节点名不生成 Is）。
            w.WriteLineComment($"// Go: {node.Key} 是多 kind 节点，逐 kind 生成 Is 函数");
            foreach (var kind in kindTypes)
            {
                w.Write($"public static bool Is{kind}(Node node) => node.Kind == Kind.{kind};");
            }

            w.Write("");
            return;
        }

        w.Write($"public static bool Is{node.Key}(Node node) => node.Kind == Kind.{node.PrimaryKind};");
        for (var i = 1; i < node.Kinds.Count; i++)
        {
            w.Write($"public static bool Is{node.Kinds[i]}(Node node) => node.Kind == Kind.{node.Kinds[i]};");
        }

        w.Write("");
    }

    private static void EmitKindAliasGuards(AstSchema schema, CodeWriter w)
    {
        // Go 的生成器跳过 JSDocSyntaxKind → IsJSDocKind：utilities.go 里手写的 IsJSDocKind 检查的是
        // JSDoc *节点* kind（FirstJSDocNode..LastJSDocNode），语义完全不同。本移植同样跳过。
        var skip = new HashSet<string> { "IsJSDocKind" };
        w.Write("");
        w.WriteLineComment("// Kind 别名守卫（Go 的 IsTokenKind/IsKeywordKind…；对应 kind_generated.go 的 Kind* 别名）");
        foreach (var alias in schema.KindAliases)
        {
            var funcName = "Is" + alias.Name.Replace("Syntax", "");
            var guard = alias;
            if (skip.Contains(funcName))
            {
                continue;
            }

            w.Write("");
            if (guard.Range is { } range)
            {
                w.WriteLineComment($"// Go: func {funcName}(kind Kind) bool {{ return kind >= Kind{range.First} && kind <= Kind{range.Last} }}");
                w.Write($"public static bool {funcName}(Kind kind) => kind >= Kind.{range.First} && kind <= Kind.{range.Last};");
            }
            else
            {
                var members = schema.ExpandKindAliasMembers(alias.Name);
                w.WriteLineComment($"// Go: func {funcName}(kind Kind) bool {{ switch kind {{ case Kind…: return true }} }}");
                w.Write($"public static bool {funcName}(Kind kind)");
                w.Write("{");
                w.Push();
                w.Write("switch (kind)");
                w.Write("{");
                w.Push();
                foreach (var member in members)
                {
                    w.Write($"case Kind.{member}:");
                }

                w.Push();
                w.Write("return true;");
                w.Pop();
                w.Pop();
                w.Write("}");
                w.Write("");
                w.Write("return false;");
                w.Pop();
                w.Write("}");
            }
        }

        w.Write("");
    }

